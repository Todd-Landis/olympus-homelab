#!/usr/bin/env bash
# Deploy from this repo to the servers over Tailscale/SSH.
#   ./deploy.sh olympus | netwatch | horae-agent | horae-theme | all
# The shared design in suite/ is copied into each app here, so edit it in one place.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build

olympus() {
  ssh helios 'mkdir -p ~/olympus/image ~/olympus/secrets && chmod 700 ~/olympus/secrets'  # before compose, or Docker makes secrets/ root-owned
  scp -q olympus/docker-compose.yml helios:olympus/
  scp -q olympus/image/Dockerfile helios:olympus/image/
  scp -q olympus/hub/app.py olympus/hub/chat.py olympus/hub/config.json helios:olympus/hub/
  scp -q olympus/hub/static/index.html suite/suite.css suite/suite.js helios:olympus/hub/static/
  scp -q olympus/agent/agent.py helios:olympus/agent/
  ssh helios 'cd ~/olympus && docker compose up -d --build && docker restart olympus olympus-agent >/dev/null'
  echo "olympus: deployed"
}
netwatch() {
  scp -q pihole-watch/docker-compose.yml helios:pihole-watch/
  scp -q pihole-watch/app/app.py helios:pihole-watch/app/
  scp -q pihole-watch/app/static/index.html suite/suite.css suite/suite.js helios:pihole-watch/app/static/
  ssh helios 'cd ~/pihole-watch && docker compose up -d && docker restart pihole-watch >/dev/null'
  echo "network watch: deployed"
}
horae_agent() {
  scp -q olympus/agent-horae/docker-compose.yml synestri@horae:olympus-agent/
  scp -q olympus/agent/agent.py synestri@horae:olympus-agent/
  ssh synestri@horae 'cd ~/olympus-agent && docker compose up -d && docker restart olympus-agent >/dev/null'
  echo "horae agent: deployed"
}
horae_theme() {
  # Homepage can only load custom.css/custom.js, so bundle the suite into them.
  { echo '/* GENERATED by deploy.sh: suite/suite.css + suite/overrides.css */'; grep -v '^\.grid { display: grid; gap: 14px; }' suite/suite.css; cat suite/overrides.css; } > build/custom.css
  { echo '// GENERATED by deploy.sh: suite/suite.js + suite/mount.js'; cat suite/suite.js; cat suite/mount.js; } > build/custom.js
  scp -q build/custom.css build/custom.js horae/homepage/*.yaml synestri@horae:/opt/pihub/homepage/
  echo "horae theme: deployed"
}

case "${1:-}" in
  olympus) olympus ;;
  netwatch) netwatch ;;
  horae-agent) horae_agent ;;
  horae-theme) horae_theme ;;
  all) olympus; netwatch; horae_agent; horae_theme ;;
  *) echo "usage: $0 olympus|netwatch|horae-agent|horae-theme|all"; exit 1 ;;
esac
