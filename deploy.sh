#!/usr/bin/env bash
# Deploy from this repo to the servers over Tailscale/SSH.
#   ./deploy.sh olympus | netwatch | horae-agent | horae-stack | horae-theme | horae-ha | hephaestus-agent | adult | adult-netwatch | all
# The shared design in suite/ is copied into each app here, so edit it in one place.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build

olympus() {
  ssh helios 'mkdir -p ~/olympus/image ~/olympus/secrets && chmod 700 ~/olympus/secrets'  # before compose, or Docker makes secrets/ root-owned
  scp -q olympus/docker-compose.yml helios:olympus/
  scp -q olympus/image/Dockerfile helios:olympus/image/
  scp -q olympus/hub/app.py olympus/hub/chat.py olympus/hub/config.json helios:olympus/hub/
  scp -q olympus/hub/static/index.html olympus/hub/static/viz.js suite/suite.css suite/suite.js suite/vendor/echarts-6.1.0.min.js helios:olympus/hub/static/
  scp -q olympus/agent/agent.py helios:olympus/agent/
  ssh helios 'cd ~/olympus && docker compose up -d --build && docker restart olympus olympus-agent >/dev/null'
  echo "olympus: deployed"
}
netwatch() {
  scp -q pihole-watch/docker-compose.yml helios:pihole-watch/
  scp -q pihole-watch/app/app.py pihole-watch/app/purge.py helios:pihole-watch/app/
  scp -q pihole-watch/app/static/index.html suite/suite.css suite/suite.js helios:pihole-watch/app/static/
  ssh helios 'cd ~/pihole-watch && docker compose up -d && docker restart pihole-watch >/dev/null'
  echo "network watch: deployed"
}
horae_agent() {
  scp -q olympus/agent-horae/docker-compose.yml synestri@horae:olympus-agent/
  scp -q olympus/agent/agent.py synestri@horae:olympus-agent/
  ssh synestri@horae 'cd ~/olympus-agent && docker compose up -d && docker restart olympus-agent >/dev/null'
  echo "horae agent: deployed"
}
horae_stack() {
  scp -q horae/stack/docker-compose.yml synestri@horae:/opt/pihub/
  scp -q horae/scripts/matter-setup.sh synestri@horae:
  # The Matter data dir needs root to create; until then, leave the stack alone.
  # .env (Pi-hole password) is root-only, so applying the stack needs sudo on the Pi.
  if ssh synestri@horae 'test -d /opt/pihub/matter'; then
    echo "horae stack: files copied. Apply on the Pi:  ssh synestri@horae, then  sudo bash -c 'cd /opt/pihub && docker compose up -d'"
  else
    echo "horae stack: files copied. First time: ssh horae, then run  sudo bash ~/matter-setup.sh"
  fi
}

hephaestus_agent() {
  ssh synestri@hephaestus 'mkdir -p ~/olympus-agent'
  scp -q olympus/agent-hephaestus/docker-compose.yml synestri@hephaestus:olympus-agent/
  scp -q olympus/agent/agent.py synestri@hephaestus:olympus-agent/
  ssh synestri@hephaestus 'cd ~/olympus-agent && docker compose up -d && docker restart olympus-agent >/dev/null'
  echo "hephaestus agent: deployed"
}
horae_theme() {
  # Homepage can only load custom.css/custom.js, so bundle the suite into them.
  { echo '/* GENERATED by deploy.sh: suite/suite.css + suite/overrides.css */'; grep -v '^\.grid { display: grid; gap: 14px; }' suite/suite.css; cat suite/overrides.css; } > build/custom.css
  { echo '// GENERATED by deploy.sh: suite/suite.js + suite/mount.js'; cat suite/suite.js; cat suite/mount.js; } > build/custom.js
  scp -q build/custom.css build/custom.js horae/homepage/*.yaml synestri@horae:/opt/pihub/homepage/
  echo "horae theme: deployed"
}
horae_ha() {
  # Home Assistant's config dir is root-owned, so this only copies; ha-theme.sh (sudo) installs and checks it.
  ssh synestri@horae 'mkdir -p ~/olympus-ha'
  scp -q horae/homeassistant/themes/olympus.yaml horae/homeassistant/www/olympus/fonts.js horae/scripts/ha-theme.sh synestri@horae:olympus-ha/
  echo "home assistant theme: files copied. Apply on the Pi:  ssh synestri@horae, then  sudo bash ~/olympus-ha/ha-theme.sh"
}
reach() {  # fail before changing anything if a machine can't be reached
  local h
  for h in "$@"; do
    # twice: the Mac's Tailscale often drops the first packets after being idle, then answers
    ssh -o ConnectTimeout=8 -o BatchMode=yes "$h" true 2>/dev/null || ssh -o ConnectTimeout=8 -o BatchMode=yes "$h" true 2>/dev/null || {
      echo "Can't reach $h over SSH ($(ssh -G "$h" | awk '/^hostname /{print $2}')). Is Tailscale connected on this Mac (menu bar icon)?"; exit 1; }
  done
}
adult() {
  # Adult sites: remove every lookup of them from Pi-hole's and Network Watch's history for good, then block them.
  # One list for all of it: the copy Network Watch tags "adult" with (OISD NSFW), so both forget exactly the same sites.
  # Files go over plain ssh (cat), not scp: macOS' scp failed on a download with a bare "Connection closed".
  reach helios synestri@horae
  echo "== [1/3] Copy the script and the list to horae"
  ssh synestri@horae 'mkdir -p ~/olympus-adult && rm -f ~/olympus-adult/adult.txt'
  ssh synestri@horae 'cat > ~/olympus-adult/adult-content.sh' < horae/scripts/adult-content.sh
  if ssh helios 'cat ~/pihole-watch/data/categories/adult.txt' > build/adult.txt && [[ -s build/adult.txt ]]; then
    ssh synestri@horae 'cat > ~/olympus-adult/adult.txt' < build/adult.txt
    echo "   Network Watch's copy of the list: $(wc -l < build/adult.txt | tr -d ' ') lines"
  else
    echo "   Couldn't get Network Watch's copy of the list from helios; the Pi will download it itself."
  fi
  rm -f build/adult.txt
  echo "== [2/3] Pi-hole on horae (asks for the Pi's sudo password)"
  # Pi-hole first: Network Watch re-reads the last minute from it on start.
  ssh -t synestri@horae 'sudo bash ~/olympus-adult/adult-content.sh'
  echo "== [3/3] Network Watch on helios"
  adult_netwatch
  echo "adult sites: gone from history, blocked from now on. Backups of both databases as they were are listed above;"
  echo "  delete them once you're happy:  ssh helios 'rm -v ~/pihole-watch/data/watch.db.before-adult-purge-*'"
  echo "                                   ssh -t horae \"sudo sh -c 'rm -v /root/pihole-FTL.db.before-adult-purge-*'\""
}
adult_netwatch() {
  # Network Watch's part alone (run after Pi-hole's): ./deploy.sh adult-netwatch
  reach helios
  ssh helios 'cat > ~/pihole-watch/app/purge.py' < pihole-watch/app/purge.py
  ssh helios 'cd ~/pihole-watch && docker compose stop pihole-watch >/dev/null 2>&1 &&
    docker compose run --rm --no-deps --name pihole-watch-purge pihole-watch python -u purge.py adult; rc=$?; docker compose up -d pihole-watch >/dev/null 2>&1; exit $rc'
}

case "${1:-}" in
  olympus) olympus ;;
  netwatch) netwatch ;;
  horae-agent) horae_agent ;;
  horae-stack) horae_stack ;;
  horae-theme) horae_theme ;;
  horae-ha) horae_ha ;;
  adult) adult ;;
  adult-netwatch) adult_netwatch ;;
  hephaestus-agent) hephaestus_agent ;;
  all) olympus; netwatch; horae_agent; horae_theme ;;
  *) echo "usage: $0 olympus|netwatch|horae-agent|horae-stack|horae-theme|horae-ha|hephaestus-agent|adult|adult-netwatch|all"; exit 1 ;;
esac
